import os
from langchain_community.chat_models import ChatOpenAI
from langchain_core.messages import HumanMessage

class AnswerGenerator:
    def __init__(self):
        # ==========================================
        # 【关键修改】初始化云端大模型 (替换原来的 Ollama)
        # ==========================================
        
        # 1. 设置 API 地址 (小米专属地址)
        # 注意：如果 search.py 里加了 os.environ，这里其实可以省略，但写在这里更保险
        api_base_url = "https://api.mimo.com/v1" # <--- 请替换为小米邮件里的真实地址
        
        # 2. 设置 API Key (小米专属 Key)
        # 建议通过环境变量设置，或者直接填在这里
        api_key = os.getenv("XIAOMI_API_KEY", "你的小米API_KEY") # <--- 请替换为真实 Key
        
        # 3. 初始化模型
        # 注意：model_name 需要根据小米平台支持的模型填写，例如 "mimo-7b" 或 "gpt-4o"
        self.llm = ChatOpenAI(
            model_name="mimo-7b",      # <--- 确认小米支持的模型名称
            temperature=0.3,           # 保持严谨
            api_key=api_key,
            base_url=api_base_url,     # 核心修改：指向小米
            timeout=120
        )
        print(f">>> 已初始化云端模型 (Base URL: {api_base_url})")

    def generate(self, user_question, kg_result, rag_context):
        """
        使用云端 API 生成回答
        """
        
        # ==========================================
        # 1. 构建提示词 (保持之前的逻辑不变)
        # ==========================================
        prompt_template = """
### 角色设定
你是一名精通中国环境法与青藏高原生态保护政策的资深法律顾问。

你的回答必须：
- 严谨
- 准确
- 法律优先级明确
- 禁止事项优先
- 严禁出现模糊结论

你尤其需要注意：

系统提供的法条已经经过：

1. 向量语义匹配
2. 政策约束感知重排序（Policy-aware Rerank）
3. 法律效力优先级排序

因此：

排序靠前的法条，
代表：

- 法律效力更高
- 政策约束更强
- 条款更具体
- 更适用于当前生态准入场景

你必须优先采纳靠前证据。

--------------------------------------------------

### 输入数据

1. 用户提问
{user_question}

--------------------------------------------------

2. 图谱硬规则（最高优先级）
{kg_result}

--------------------------------------------------

3. 经过“政策约束感知重排序”后的法条证据
（已综合考虑：
语义相关性、
政策强度、
法律效力、
条款具体性、
禁止优先原则）

{rag_context}

--------------------------------------------------

### 法律推理规则（必须严格遵守）

1. 图谱规则优先
如果图谱中存在明确“禁止/限制/允许”规则：
必须优先采纳，
不得被普通法条覆盖。

--------------------------------------------------

2. 禁止优先原则
若多个法条冲突：

禁止 > 限制 > 鼓励

即：

只要存在明确禁止性规定，
不得因为鼓励性政策而放宽。

--------------------------------------------------

3. 特别法优于一般法

优先采纳：

- 青藏高原专项法规
- 三江源专项法规
- 生态保护专项法规

而非普通地方性通知。

--------------------------------------------------

4. 新法优于旧法

优先采纳最新发布法规。

--------------------------------------------------

5. 具体条款优于原则性条款

优先采纳：

- “具体管控措施”
而不是：
- “原则/总则”

--------------------------------------------------

6. 趋势风险预警

如果：

[政策趋势信号]

显示：

监管收紧、
红线加强、
禁止增多、

则必须提高风险评级。

即使当前没有绝对禁止，
也需要提示：

“未来存在进一步收紧风险”。

--------------------------------------------------

### 输出要求

不要输出推理过程。

严格按照以下格式输出：

### 1. 最终结论

🟢允许
或
🟡限制（需审批）
或
🔴禁止

并用一句话解释原因。

--------------------------------------------------

### 2. 核心法律依据

列出：
- 法律名称
- 条款内容
- 为什么优先适用

--------------------------------------------------

### 3. 政策趋势与合规建议

结合：
- 政策趋势
- 监管方向
- 未来风险

给出简洁专业建议。

"""

        final_prompt = prompt_template.format(
            user_question=user_question,
            kg_result=kg_result,
            rag_context=rag_context
        )

        # ==========================================
        # 2. 调用云端 API
        # ==========================================
        print(f"\n>>> 正在呼叫云端大模型...")
        
        try:
            # 使用 LangChain 的 invoke 方法发送消息
            response = self.llm.invoke([HumanMessage(content=final_prompt)])
            
            # 返回内容
            return response.content
            
        except Exception as e:
            return f"[错误] 调用云端模型失败: {str(e)}。请检查 API Key 和网络连接。"