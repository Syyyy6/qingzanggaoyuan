import os

# 推荐使用新版 LangChain OpenAI
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage


class AnswerGenerator:

    def __init__(self):

        # ==========================================
        # 阿里云百炼 API 配置
        # ==========================================

        # 百炼兼容 OpenAI 的 API 地址
        api_base_url = "https://dashscope.aliyuncs.com/compatible-mode/v1"

        # ==========================================
        # 初始化大模型
        # ==========================================

        self.llm = ChatOpenAI(
            model="qwen-turbo",
            temperature=0.2,   # 法律场景建议低温度
            api_key="sk-f4aa0d879f9a4a1d8707e00de856488d",
            base_url=api_base_url,
            timeout=120
        )

        print(">>> 已初始化阿里云百炼模型")
        print(f">>> Base URL: {api_base_url}")

    # ==========================================
    # 生成回答
    # ==========================================
    def generate(
        self,
        user_question,
        kg_result,
        rag_context,
        forced_decision=None
    ):

        # ==========================================
        # Prompt（图谱主导版）
        # ==========================================

        prompt_template = """
### 角色设定

你是一名精通：

- 中国环境法
- 青藏高原生态保护法
- 国家生态保护红线制度
- 自然保护区管理制度
- 国家公园生态准入制度

的资深生态环境法律顾问。

你的回答必须：

- 严谨
- 准确
- 专业
- 结论明确
- 禁止模糊表达
- 禁止推翻系统结论

--------------------------------------------------

### 系统最高规则（必须严格遵守）

系统已经通过：

【生态环境准入知识图谱】

完成了最终准入判定。

因此：

图谱中的：

- 禁止
- 限制
- 允许

属于：

【最终准入结论】

你不得：

- 修改图谱结论
- 弱化图谱结论
- 使用普通法规推翻图谱结论
- 使用鼓励性政策覆盖禁止性规则
- 出现“原则上允许”等模糊表述

你的职责仅包括：

1. 解释图谱结论的法律原因
2. 提供相关法律依据
3. 分析监管趋势
4. 提供合规建议

--------------------------------------------------

### 输入数据

【用户问题】
{user_question}

--------------------------------------------------

【图谱最终规则（最高优先级）】
{kg_result}
--------------------------------------------------

【系统强制最终裁决】

{forced_decision}

注意：

这是系统已经确定的最终准入结论。

你只能：

- 解释原因
- 补充法律依据
- 分析趋势

不得：

- 修改结论
- 弱化结论
- 输出相反结论
--------------------------------------------------

【法律法规解释依据 + 趋势依据】
{rag_context}

--------------------------------------------------

### 法律适用原则（必须严格遵守）

1. 图谱规则优先

图谱中的准入结论，
属于最终生态准入规则。

不得被普通法规覆盖。

--------------------------------------------------

2. 禁止优先原则

禁止 > 限制 > 鼓励

只要存在明确禁止性规定，
不得放宽解释。

--------------------------------------------------

3. 特别法优于一般法

优先采纳：

- 青藏高原生态保护法
- 国家生态保护红线制度
- 自然保护区相关法规
- 国家公园相关法规

--------------------------------------------------

4. 新法优于旧法

优先参考最新法规。

--------------------------------------------------

5. 具体条款优于原则性条款

优先引用：

- 具体管控措施
- 明确禁止性条款

--------------------------------------------------

6. 趋势风险预警

如果监管趋势显示：

- 红线收紧
- 禁止增加
- 管控加强

则必须提高风险等级。

--------------------------------------------------

### 关键要求（非常重要）

你必须明确区分：

【最终准入结论】
与
【法律解释】

其中：

- 最终准入结论：
  只能来自图谱规则

- 向量检索法规：
  只能用于：
    - 法律解释
    - 趋势分析
    - 风险说明
    - 补充依据

不得：

使用向量法规改变图谱结论。

--------------------------------------------------

### 输出要求

不要输出推理过程。

严格按照以下格式输出：

### 1. 图谱准入结论（最终结论）

直接输出：

🟢允许
或
🟡限制（需审批）
或
🔴禁止

并用一句话说明原因。

--------------------------------------------------

### 2. 准入依据（直接依据）

必须优先引用：

- 图谱中的 source
- 准入清单条款
- 管控规则

这是最终结论的直接来源。

--------------------------------------------------

### 3. 相关法律解释

结合系统提供的法律法规：

- 解释为什么会形成该准入限制
- 说明生态保护逻辑
- 说明监管依据

注意：

这里属于“法律解释”，
不得改变图谱最终结论。

--------------------------------------------------

### 4. 政策趋势与合规建议

结合：

- 政策趋势
- 监管方向
- 风险等级

给出专业建议。

如果属于：

- 红线区域
- 自然保护区
- 国家重点生态功能区

需要明确提示：

未来监管可能进一步收紧。

--------------------------------------------------

### 输出风格要求

你的回答必须：

- 使用正式法律语言
- 不得口语化
- 不得使用“大概”“可能”“似乎”
- 必须体现法律确定性
- 必须体现生态保护优先原则
"""

        # ==========================================
        # Prompt 拼接
        # ==========================================

        final_prompt = prompt_template.format(
        user_question=user_question,
        kg_result=kg_result,
        rag_context=rag_context,
        forced_decision=forced_decision
        )

        # ==========================================
        # 调用百炼 API
        # ==========================================

        print("\n>>> 正在调用阿里云百炼大模型...")

        try:

            response = self.llm.invoke(
                [HumanMessage(content=final_prompt)]
            )

            return response.content

        except Exception as e:

            return f"""
[错误] 调用阿里云百炼失败：

{str(e)}

请检查：

1. API Key 是否正确
2. 是否开通 DashScope 百炼服务
3. 网络是否正常
4. model 名称是否可用
"""